#!/usr/bin/env python3
"""Generate app-side key predicates from Grove's canonical shortcut catalog."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_APPS = {
    "codex": ROOT.parent / "codex",
    "pixie": ROOT.parent / "pixie",
    "siren": ROOT.parent / "siren",
    "scroll": ROOT.parent / "scroll",
    "wisp": ROOT.parent / "wisp",
}


def rust_module(version: int, next_binding: str, previous_binding: str) -> str:
    if next_binding != "Tab" or previous_binding != "Shift+Tab":
        raise ValueError("v1 generator supports only Grove's Tab / Shift+Tab cycle bindings")
    return f'''// Generated by faeOS/tools/sync-keyboard-shortcuts.py; do not edit by hand.
use crossterm::event::{{KeyCode, KeyModifiers}};

pub const CYCLE_NEXT: &str = "{next_binding}";
pub const CYCLE_PREVIOUS: &str = "{previous_binding}";

pub fn is_cycle_next(code: KeyCode, modifiers: KeyModifiers) -> bool {{
    match CYCLE_NEXT {{
        "Tab" => {{
            code == KeyCode::Tab
                && !modifiers.intersects(
                    KeyModifiers::SHIFT
                        | KeyModifiers::CONTROL
                        | KeyModifiers::ALT
                        | KeyModifiers::SUPER,
                )
        }}
        _ => false,
    }}
}}

pub fn is_cycle_previous(code: KeyCode, modifiers: KeyModifiers) -> bool {{
    let plain_modifiers =
        !modifiers.intersects(KeyModifiers::CONTROL | KeyModifiers::ALT | KeyModifiers::SUPER);
    match CYCLE_PREVIOUS {{
        "Shift+Tab" => {{
            plain_modifiers
                && (code == KeyCode::BackTab
                    || (code == KeyCode::Tab && modifiers.intersects(KeyModifiers::SHIFT)))
        }}
        _ => false,
    }}
}}

#[cfg(test)]
mod tests {{
    use super::*;

    #[test]
    fn cycle_bindings_follow_the_grove_catalog() {{
        assert_eq!(CYCLE_NEXT, "Tab");
        assert_eq!(CYCLE_PREVIOUS, "Shift+Tab");
        assert!(is_cycle_next(KeyCode::Tab, KeyModifiers::NONE));
        assert!(!is_cycle_next(KeyCode::Tab, KeyModifiers::SHIFT));
        assert!(!is_cycle_next(KeyCode::Tab, KeyModifiers::CONTROL));
        assert!(!is_cycle_next(KeyCode::BackTab, KeyModifiers::NONE));
        assert!(is_cycle_previous(KeyCode::BackTab, KeyModifiers::NONE));
        assert!(is_cycle_previous(KeyCode::BackTab, KeyModifiers::SHIFT));
        assert!(is_cycle_previous(KeyCode::Tab, KeyModifiers::SHIFT));
        assert!(!is_cycle_previous(KeyCode::Tab, KeyModifiers::NONE));
        assert!(!is_cycle_previous(KeyCode::BackTab, KeyModifiers::CONTROL));
        assert!(!is_cycle_previous(
            KeyCode::BackTab,
            KeyModifiers::SHIFT | KeyModifiers::ALT
        ));
    }}
}}
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated app modules are stale")
    parser.add_argument("--apps", nargs="*", choices=DEFAULT_APPS, default=list(DEFAULT_APPS))
    args = parser.parse_args()

    catalog_path = ROOT / "config/keyboard-shortcuts.json"
    try:
        catalog = json.loads(catalog_path.read_text(encoding="utf-8"))
        if catalog["version"] != 1:
            raise ValueError("unsupported keyboard catalog version")
        actions = catalog["actions"]
        output = rust_module(
            catalog["version"],
            actions["cycle_next"]["binding"],
            actions["cycle_previous"]["binding"],
        )
    except (OSError, KeyError, TypeError, ValueError, json.JSONDecodeError) as error:
        print(f"keyboard shortcuts: invalid {catalog_path}: {error}", file=sys.stderr)
        return 1

    failed = False
    for app in args.apps:
        path = DEFAULT_APPS[app] / "src/grove_keys.rs"
        if args.check:
            try:
                existing = path.read_text(encoding="utf-8")
            except OSError as error:
                print(f"keyboard shortcuts: cannot read {path}: {error}", file=sys.stderr)
                failed = True
                continue
            if existing != output:
                print(f"keyboard shortcuts: stale generated module: {path}", file=sys.stderr)
                failed = True
        else:
            try:
                path.write_text(output, encoding="utf-8")
            except OSError as error:
                print(f"keyboard shortcuts: cannot write {path}: {error}", file=sys.stderr)
                failed = True
                continue
            print(f"generated {path}")
    return int(failed)


if __name__ == "__main__":
    raise SystemExit(main())
